"""Generate firmware/NN_live_rom.h from the hls4ml weight files.

NN_live accumulates the first layer (1540 -> 4, ternary) one sample at a time,
so it needs, per sample n, the eight weights that multiply I_n and Q_n for the
four hidden units. This packs them into one 16-bit ROM word per sample:

    bits [4u+1 : 4u]   weight of I_n for unit u   (2-bit two's complement)
    bits [4u+3 : 4u+2] weight of Q_n for unit u

Layout facts this relies on (both checked end to end by the csim, which
compares every shot against hls4ml's own NN()):
  * NN_axi's LOAD_L leaves input index 2n = I_n and 2n+1 = Q_n
    (word bits [15:0] = I, [31:16] = Q).
  * config2 uses the resource strategy at reuse_factor 1, whose
    dense_resource_rf_leq_nin reads weights[u*1540 + i] (hls4ml transposes
    the matrix for this strategy; the header comment still prints the
    original [1540, 4] shape).

It also sizes the accumulator: with |I|, |Q| <= 32768 and ternary weights,
|sum_u| <= 32768 * sum_i |w[u,i]| + |b2[u]|, so ACC_W bits hold every sum
exactly and the narrow accumulator is bit-identical to hls4ml's
ap_fixed<48,32> one.

"""
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
W = HERE / "firmware" / "weights"
N_IN, N_OUT, N_SAMP = 1540, 4, 770

def load_txt(name):
    return np.array([float(t) for t in (W / name).read_text().split(",")])

w2 = load_txt("w2.txt")
b2 = load_txt("b2.txt")
assert w2.size == N_IN * N_OUT and set(np.unique(w2)) <= {-1.0, 0.0, 1.0}
assert b2.size == N_OUT and set(np.unique(b2)) <= {-1.0, 0.0, 1.0}
w = w2.astype(int).reshape(N_OUT, N_IN)          # w[u, i] = w2[u*1540 + i]

code = {0: 0b00, 1: 0b01, -1: 0b11}
rom = []
for n in range(N_SAMP):
    word = 0
    for u in range(N_OUT):
        word |= code[w[u, 2 * n]] << (4 * u)
        word |= code[w[u, 2 * n + 1]] << (4 * u + 2)
    rom.append(word)

bound = int(max(32768 * np.abs(w[u]).sum() + abs(b2[u]) for u in range(N_OUT)))
acc_w = int(bound).bit_length() + 1             # + sign bit
nonzero = [int(np.count_nonzero(w[u])) for u in range(N_OUT)]

lines = [
    "// GENERATED by gen_live_rom.py from firmware/weights/w2.txt -- do not edit.",
    "#ifndef NN_LIVE_ROM_H_",
    "#define NN_LIVE_ROM_H_",
    "#include \"ap_int.h\"",
    "",
    f"// nonzero weights per unit: {nonzero} (total {sum(nonzero)})",
    f"// worst-case |sum| = {bound} < 2^{acc_w - 1}",
    f"#define ACC_W {acc_w}",
    "",
    "static const ap_uint<16> WROM[770] = {",
]
for k in range(0, N_SAMP, 12):
    lines.append("    " + ", ".join(f"0x{v:04x}" for v in rom[k:k + 12]) + ",")
lines += ["};", "", "#endif", ""]
(HERE / "firmware" / "NN_live_rom.h").write_text("\n".join(lines))
print(f"wrote NN_live_rom.h: {N_SAMP} words, ACC_W={acc_w}, nonzero/unit={nonzero}, bound={bound}")
